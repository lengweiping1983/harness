import {expect,it,vi} from 'vitest'
const load=vi.hoisted(()=>({echarts:vi.fn(),vega:vi.fn()}))
vi.mock('../../../node_modules/echarts/dist/echarts.min.js?raw',()=>load.echarts())
vi.mock('../../../node_modules/vega/build/vega.min.js?raw',()=>load.vega())
vi.mock('../../../node_modules/vega-lite/build/vega-lite.min.js?raw',()=>({default:'lite'}))
vi.mock('../../../node_modules/vega-embed/build/vega-embed.min.js?raw',()=>({default:'embed'}))
it('shares concurrent downloads and the Vega/Lite runtime without executing code in the host',async()=>{
 load.echarts.mockReturnValue({default:'window.hostMustNotRun=true'})
 load.vega.mockReturnValue({default:'vega'})
 const {loadChartRuntime}=await import('../chartRuntime')
 const first=loadChartRuntime('echarts'),second=loadChartRuntime('echarts')
 expect(second).toBe(first)
 expect(await first).toBe('window.hostMustNotRun=true')
 expect(load.echarts).toHaveBeenCalledTimes(1)
 const vega=loadChartRuntime('vega'),lite=loadChartRuntime('vega-lite')
 expect(vega).toBe(lite)
 expect(await lite).toBe('vega\n;\nlite\n;\nembed')
 expect(load.vega).toHaveBeenCalledTimes(1)
})
