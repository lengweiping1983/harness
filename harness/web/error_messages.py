ERROR_MESSAGE_KEYS = {code: 'ui.collaboration.error.' + code for code in _ERROR_CODES}


def public_error_message(message: str, code: str) -> str:
    """只转换消息即错误码的已知错误，保留具体诊断和未知错误。"""
    key = ERROR_MESSAGE_KEYS.get(code) if message == code else None
    return tr(key, code=code) if key else message
