"""从公共 OpenAPI 提取关键响应契约，前端无需复制字段定义。"""
import json
import re


KEYWORDS = {'$ref', 'type', 'required', 'properties', 'items', 'anyOf', 'oneOf',
            'enum', 'const', 'additionalProperties', 'minimum', 'maximum',
            'minLength', 'maxLength', 'pattern', 'minItems', 'maxItems'}


def response_contracts(document):
    """仅导出接入、提交、引导、权限、队列、连接、设置、目录和终端，保留引用的传递闭包。"""
    definitions = {}
    def compact(schema):
        if not isinstance(schema, dict):
            return schema
        result = {}
        for key, value in schema.items():
            if key not in KEYWORDS:
                continue
            if key == '$ref':
                name = value.rsplit('/', 1)[-1]
                if name not in definitions:
                    definitions[name] = {}
                    definitions[name] = compact(document['components']['schemas'][name])
                result[key] = name
            elif key == 'properties':
                result[key] = {name: compact(item) for name, item in value.items()}
            elif key in {'anyOf', 'oneOf'}:
                result[key] = [compact(item) for item in value]
            elif key in {'items', 'additionalProperties'}:
                result[key] = compact(value)
            else:
                result[key] = value
        return result
    contracts = []
    for path, operations in document['paths'].items():
        if not (path.startswith(('/api/v1/voice/','/api/v1/superagents')) or path in {'/api/v1/workspaces', '/api/v1/workspace-options', '/api/v1/sessions', '/api/v1/sessions/activity', '/api/v1/settings', '/api/v1/ui-settings', '/api/v1/plugins/skills/create', '/api/v1/plugins/skills/created', '/api/v1/plugins/agents/create', '/api/v1/plugins/agents/{name}', '/api/v1/terminal/types', '/api/v1/sessions/{session_id}/terminals', '/api/v1/sessions/{session_id}/memory/preview'} or path.startswith('/api/v1/academy/') or path.startswith('/api/v1/access/') or path.startswith('/api/v1/connection') or path.startswith('/api/v1/chatgpt') or path.startswith('/api/v1/mcp-service') or path.startswith('/api/v1/plugin-packages') or
                path.endswith(('/turns/{turn}/completion', '/turns/{turn}/run')) or re.search(r'/(runs(?:/|$)|questions(?:/|$)|decisions(?:/|$)|steer(?:/|$)|steering(?:/|$)|permissions(?:/|$)|queue$|queue-control$|queue-order$)', path)):
            continue
        pattern = '^' + re.sub(r'\{[^}]+\}', '[^/]+', path) + '$'
        for method, operation in operations.items():
            for status, response in operation.get('responses', {}).items():
                schema = response.get('content', {}).get('application/json', {}).get('schema')
                if status.startswith('2') and schema:
                    contracts.append([pattern, method.upper(), int(status), compact(schema)])
    return '// Generated by scripts/generate_protocol.py; do not edit.\n' + \
        'export const responseContracts = ' + json.dumps(contracts, ensure_ascii=False, separators=(',', ':')) + '\n' + \
        'export const responseDefinitions = ' + json.dumps(definitions, ensure_ascii=False, separators=(',', ':')) + '\n'
